/**
 * Fuzzy search to match any Indian district name, station code, or town name
 */
export function findDistrictStation(query: string): DistrictStationInfo | null {
  if (!query) return null;
  const q = query.toLowerCase().trim();

  // 1. Direct district match
  const exactDistrict = INDIAN_DISTRICTS_STATIONS.find((d) =>
    d.district.toLowerCase() === q || q.includes(d.district.toLowerCase())
  );
  if (exactDistrict) return exactDistrict;

  // 2. Station code match
  const codeMatch = INDIAN_DISTRICTS_STATIONS.find((d) =>
    d.stationCode.toLowerCase() === q || q.includes(d.stationCode.toLowerCase())
  );
  if (codeMatch) return codeMatch;

  // 3. Partial district or station name match
  return (
    INDIAN_DISTRICTS_STATIONS.find((d) =>
      d.district.toLowerCase().includes(q) ||
      d.primaryStation.toLowerCase().includes(q) ||
      d.state.toLowerCase().includes(q) ||
      d.primaryBusStand.toLowerCase().includes(q)
    ) || null
  );
}
